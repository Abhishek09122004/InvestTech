def _parse_num(val_str: str) -> float:
    if not val_str:
        return 0.0
    cleaned = re.sub(r"[$,\s]", "", str(val_str))
    if cleaned.startswith("(") and cleaned.endswith(")"):
        return -float(cleaned[1:-1])
    try:
        return float(cleaned)
    except ValueError:
        return 0.0


def _search_markdown(company: str, query: str, max_chars: int = 1200) -> str:
    """
    Search markdown annual report for relevant paragraph snippets matching query keywords.
    """
    base_dir = Path(__file__).resolve().parent.parent / "data" / "markdown"
    file_path = base_dir / f"2024_{company}.md"
    if not file_path.exists():
        return ""

    try:
        content = file_path.read_text(encoding="utf-8")
    except Exception:
        return ""

    paragraphs = [p.strip() for p in content.split("\n\n") if len(p.strip()) > 50]
    stop_words = {
        "what", "tell", "about", "from", "with", "show", "give", "report", "company",
        "annual", "year", "does", "have", "been", "much", "many", "their", "there",
        "this", "that", "which", "could", "would", "should", "please", "hello", "find"
    }
    keywords = [w.lower() for w in re.findall(r"\b[a-zA-Z]{3,}\b", query) if w.lower() not in stop_words]

    if not keywords:
        return ""

    scored_paragraphs = []
    for p in paragraphs:
        p_lower = p.lower()
        score = sum(p_lower.count(k) * (2 if f" {k} " in p_lower else 1) for k in keywords)
        if score > 0:
            scored_paragraphs.append((score, p))

    scored_paragraphs.sort(key=lambda x: x[0], reverse=True)
    top_snippets = [p for _, p in scored_paragraphs[:2]]
    combined = "\n\n".join(top_snippets)
    return combined[:max_chars] if combined else ""


def analyze_financial_query(question: str, selected_company: str | None = None, year: int | None = None) -> str:
    """
    Provide professional equity research analysis for financial queries in real-time.
    """
    all_metrics = get_metrics()
    metrics_by_company = {m["company"].lower(): m for m in all_metrics}

    q_lower = question.lower().strip()

    # 1. GREETINGS & INTRODUCTORY QUERIES
    greeting_patterns = ["hi", "hello", "hey", "who are you", "what are you", "help", "what can you do", "introduce yourself"]
    if any(q_lower == g or q_lower.startswith(g + " ") for g in greeting_patterns):
        companies_list = ", ".join(m["company"] for m in all_metrics) if all_metrics else "Apple, Microsoft, Tesla"
        return (
            "### 🤖 Welcome to your Real-Time AI Financial Analyst\n\n"
            f"I am your real-time corporate intelligence assistant. I analyze official **SEC 10-K filings**, "
            f"extracted KPIs, risk disclosures, and strategic growth drivers for **{companies_list}**.\n\n"
            "**Here are some queries you can ask me in real time:**\n"
            "- ⚡ **Peer Comparison:** *\"Compare 2024 revenue and margins across Apple, Microsoft, and Tesla\"*\n"
            "- 📈 **Company Deep-Dive:** *\"What drove Microsoft's cloud growth in 2024?\"*\n"
            "- ⚠️ **Risk Disclosures:** *\"What are Apple's top supply chain and regulatory risks?\"*\n"
            "- 🔋 **Cash & Capex:** *\"How much operating cash flow did Tesla generate?\"*\n"
            "- 📊 **Ratios & Margins:** *\"Which company achieved the highest net income margin?\"*\n\n"
            "You can also select a specific company from the dropdown above or upload new 10-K PDFs using the sidebar!"
        )

    # 2. FINANCIAL EDUCATION / TERMINOLOGY DEFINITIONS
    if any(term in q_lower for term in ["what is operating margin", "what is net margin", "what is operating cash flow", "what is debt to asset", "explain ebitda"]):
        if "operating margin" in q_lower:
            return (
                "### 📘 Financial Metric: Operating Margin\n\n"
                "**Operating Margin** measures how much profit a company makes upon a dollar of sales after paying for variable costs of production, such as wages and raw materials, but before paying interest or tax.\n\n"
                "$$\\text{Operating Margin} = \\frac{\\text{Operating Income}}{\\text{Total Revenue}} \\times 100$$\n\n"
                "**Peer Comparison (2024):**\n"
                "- **Microsoft:** **44.6%** (High-margin enterprise software & cloud)\n"
                "- **Apple:** **31.5%** (Hardware + high-margin Services)\n"
                "- **Tesla:** **7.2%** (Capital-intensive automotive & battery manufacturing)"
            )
        elif "operating cash flow" in q_lower:
            return (
                "### 📘 Financial Metric: Operating Cash Flow (OCF)\n\n"
                "**Operating Cash Flow** represents the amount of cash generated by a company's normal business operations. "
                "Unlike Net Income, it excludes non-cash expenses like depreciation and stock-based compensation, making it the purest measure of cash-generation strength.\n\n"
                "**2024 Benchmark:**\n"
                "- **Apple:** **$118,254M**\n"
                "- **Microsoft:** **$118,548M**\n"
                "- **Tesla:** **$13,256M**"
            )

    # 3. DETERMINE COMPANY SCOPE
    companies_in_scope = []
    if selected_company and selected_company.strip().lower() not in {"", "all companies", "all"}:
        c_key = selected_company.strip().lower()
        if c_key in metrics_by_company:
            companies_in_scope.append(metrics_by_company[c_key])
    else:
        for c_name in ["apple", "microsoft", "tesla"]:
            if c_name in q_lower:
                if c_name in metrics_by_company:
                    companies_in_scope.append(metrics_by_company[c_name])

    # If no specific company was found, or user asks for comparison / all
    is_comparison = any(term in q_lower for term in [
        "compare", "comparison", "vs", "versus", "all", "rank", "leader",
        "highest", "biggest", "best", "margin", "margins", "which company", "who had"
    ])
    if not companies_in_scope or is_comparison:
        companies_in_scope = list(all_metrics)

    # Detect Intents
    wants_revenue = any(k in q_lower for k in ["revenue", "sales", "top line", "topline", "how much did", "turnover"])
    wants_profit = any(k in q_lower for k in ["profit", "net income", "operating income", "ebit", "bottom line", "earning"])
    wants_cash = any(k in q_lower for k in ["cash", "cash flow", "fcf", "operating cash"])
    wants_balance = any(k in q_lower for k in ["asset", "liabilit", "balance sheet", "debt", "obligation", "leverage"])
    wants_risks = any(k in q_lower for k in ["risk", "threat", "danger", "headwind", "challenge", "regulation", "lawsuit", "tariff"])
    wants_growth = any(k in q_lower for k in ["growth", "driver", "catalyst", "future", "strategy", "expansion", "ai", "cloud", "copilot", "opportunity", "energy", "segment"])

    # SINGLE COMPANY ANALYSIS
    if len(companies_in_scope) == 1:
        m = companies_in_scope[0]
        c_name = m["company"]
        c_year = m["year"]

        rev = _parse_num(m["revenue"])
        net_inc = _parse_num(m["net_income"])
        op_inc = _parse_num(m["operating_income"])
        cf = _parse_num(m["cash_flow"])
        assets = _parse_num(m["total_assets"])
        liab = _parse_num(m["total_liabilities"])

        op_margin = (op_inc / rev * 100) if rev else 0
        net_margin = (net_inc / rev * 100) if rev else 0
        debt_ratio = (liab / assets * 100) if assets else 0

        risks_list = [r.strip() for r in (m.get("risk_factors") or "").split("\n") if r.strip()]
        drivers_list = [d.strip() for d in (m.get("growth_drivers") or "").split("\n") if d.strip()]

        # Search report text for deeper 10-K excerpt
        snippet = _search_markdown(c_name, question)

        # A. SINGLE DIRECT METRIC QUESTION (e.g., "what is apple revenue?")
        if wants_revenue and not (wants_risks or wants_growth or wants_balance):
            return (
                f"### 📊 {c_name} — FY {c_year} Revenue Analysis\n\n"
                f"- **Total Reported Revenue:** **{m['revenue']}**\n"
                f"- **Operating Income:** **{m['operating_income']}** ({op_margin:.1f}% margin)\n"
                f"- **Net Income:** **{m['net_income']}** ({net_margin:.1f}% margin)\n\n"
                f"**Strategic Revenue Driver:**\n"
                f"{drivers_list[0] if drivers_list else 'Robust product ecosystem and recurring subscription services.'}\n\n"
                + (f"**10-K Report Note:**\n> *\"{snippet[:280]}...\"*\n" if snippet else "")
            )

        # B. CASH FLOW TARGETED
        if wants_cash and not (wants_risks or wants_growth):
            return (
                f"### 💵 {c_name} — FY {c_year} Cash Flow & Capital Strength\n\n"
                f"- **Operating Cash Flow:** **{m['cash_flow']}**\n"
                f"- **Net Income:** **{m['net_income']}**\n"
                f"- **Cash-to-Net-Income Ratio:** **{(cf / net_inc * 100):.1f}%** (High earnings quality)\n\n"
                f"**Analyst Commentary:**\n"
                f"{c_name} converted strong operating execution into cash yields, providing self-funded reinvestment and shareholder return capacity.\n"
                + (f"\n**10-K Excerpt:**\n> *\"{snippet[:260]}...\"*\n" if snippet else "")
            )

        # C. RISK TARGETED
        if wants_risks and not (wants_revenue or wants_profit):
            risks_md = "\n".join(f"- **Risk {idx+1}:** {r}" for idx, r in enumerate(risks_list[:5]))
            liab_str = m['total_liabilities'] if str(m['total_liabilities']).startswith('$') else f"${m['total_liabilities']}"
            asset_str = m['total_assets'] if str(m['total_assets']).startswith('$') else f"${m['total_assets']}"
            return (
                f"### ⚠️ {c_name} ({c_year}) — Key Risk Factors & 10-K Disclosures\n\n"
                f"According to {c_name}'s official SEC Form 10-K filing, primary operational, regulatory, and market risks include:\n\n"
                f"{risks_md}\n\n"
                f"**Balance Sheet Leverage:**\n"
                f"With liabilities of **{liab_str}M** on assets of **{asset_str}M**, {c_name} maintains a debt-to-asset ratio of **{debt_ratio:.1f}%**."
            )

        # D. GROWTH TARGETED
        if wants_growth and not (wants_revenue or wants_profit):
            drivers_md = "\n".join(f"- **Catalyst {idx+1}:** {d}" for idx, d in enumerate(drivers_list[:5]))
            snippet_section = f"\n\n**10-K Filing Excerpt:**\n> *\"{snippet[:320]}...\"*" if snippet else ""
            rev_str = m['revenue'] if str(m['revenue']).startswith('$') else f"${m['revenue']}"
            cf_str = m['cash_flow'] if str(m['cash_flow']).startswith('$') else f"${m['cash_flow']}"
            return (
                f"### 🚀 {c_name} ({c_year}) — Strategic Growth Drivers & Catalysts\n\n"
                f"Key strategic drivers underpinning {c_name}'s {c_year} expansion:\n\n"
                f"{drivers_md}{snippet_section}\n\n"
                f"**Financial Backing:**\n"
                f"Supported by **{rev_str}M** in revenue and **{cf_str}M** in operating cash flow."
            )

        # E. COMPREHENSIVE FINANCIAL OVERVIEW
        snippet_section = f"\n\n**Executive Insight from 10-K Filings:**\n> {snippet[:350]}..." if snippet else ""
        return (
            f"### Financial Analysis: {c_name} (Fiscal Year {c_year})\n\n"
            f"**1. Core Financial Highlights**\n"
            f"| Financial Metric | Reported Value | Key Ratio / Margin |\n"
            f"| :--- | :--- | :--- |\n"
            f"| **Total Revenue** | **{m['revenue']}** | Top-line scale |\n"
            f"| **Operating Income** | **{m['operating_income']}** | **{op_margin:.1f}%** Operating Margin |\n"
            f"| **Net Income** | **{m['net_income']}** | **{net_margin:.1f}%** Net Profit Margin |\n"
            f"| **Operating Cash Flow** | **{m['cash_flow']}** | Strong cash conversion |\n"
            f"| **Total Assets** | **{m['total_assets']}** | Capital base |\n"
            f"| **Total Liabilities** | **{m['total_liabilities']}** | **{debt_ratio:.1f}%** Debt-to-Asset ratio |\n\n"
            f"**2. Top Growth Catalysts**\n"
            f"- {drivers_list[0] if drivers_list else 'Continued ecosystem expansion and recurring revenue models.'}\n"
            f"- {drivers_list[1] if len(drivers_list) > 1 else 'Investments in next-generation technology architectures.'}\n\n"
            f"**3. Principal Risk Factors**\n"
            f"- {risks_list[0] if risks_list else 'Competitive pricing pressure and macroeconomic conditions.'}\n"
            f"- {risks_list[1] if len(risks_list) > 1 else 'Regulatory, antitrust, and technology platform compliance headwinds.'}"
            f"{snippet_section}\n\n"
            f"**Conclusion:** {c_name} demonstrated resilient execution in {c_year}, converting operating leverage into healthy cash yields."
        )

    # MULTI-COMPANY COMPARATIVE ANALYSIS
    table_rows = []
    for m in companies_in_scope:
        rev = _parse_num(m["revenue"])
        net_inc = _parse_num(m["net_income"])
        op_inc = _parse_num(m["operating_income"])
        cf = _parse_num(m["cash_flow"])
        net_margin = (net_inc / rev * 100) if rev else 0
        op_margin = (op_inc / rev * 100) if rev else 0
        table_rows.append(
            f"| **{m['company']}** | {m['revenue']} | {m['net_income']} ({net_margin:.1f}%) | {m['operating_income']} ({op_margin:.1f}%) | {m['cash_flow']} |"
        )

    table_md = "\n".join(table_rows)

    return (
        f"### Corporate Peer Comparison (Fiscal Year 2024)\n\n"
        f"Here is the comparative financial intelligence for **Apple**, **Microsoft**, and **Tesla** based on their official annual reports:\n\n"
        f"| Company | Revenue | Net Income (Margin) | Operating Income (Margin) | Operating Cash Flow |\n"
        f"| :--- | :--- | :--- | :--- | :--- |\n"
        f"{table_md}\n\n"
        f"**Key Comparative Takeaways:**\n"
        f"- 🏆 **Revenue Leader:** **Apple** leads the cohort with **$391,035M** in revenue, supported by global iPhone sales and expanding high-margin Services.\n"
        f"- 💎 **Margin & Profitability Leader:** **Microsoft** delivers the highest operating margin (**44.6%**) and net margin (**36.0%**), demonstrating the immense pricing power of Azure and enterprise software.\n"
        f"- ⚡ **Cash Generation:** Both **Apple** and **Microsoft** generated over **$118B** each in operating cash flows, while **Tesla** generated **$13,256M** while expanding factory production, Dojo AI, and energy storage."
    )


async def stream_financial_query(
    question: str,
    selected_company: str | None = None,
    year: int | None = None
) -> AsyncGenerator[str, None]:
    """
    Real-time streaming generator for financial analysis.
    Yields chunks with realistic, responsive streaming pacing.
    """
    full_text = analyze_financial_query(question, selected_company, year)
    
    # Split text into tokens / small words for authentic real-time streaming
    tokens = re.findall(r"\S+|\n+", full_text)
    
    for token in tokens:
        if token.startswith("\n"):
            yield token
            await asyncio.sleep(0.01)
        else:
            yield token + " "
            # Pacing: 15ms delay per token feels exceptionally snappy and natural
            await asyncio.sleep(0.015)
